/**
 * The README's CLI reference is generated from TOOL_DEFINITIONS so it cannot drift from the
 * commands the CLI and MCP server actually expose. `bun run docs:sync` rewrites the block;
 * the readme-sync test fails if the committed block is stale.
 */
import { formatHelp } from './cli'
import { TOOL_DEFINITIONS } from './tools'

export const HELP_START = '<!-- cli-help:start (generated by "bun run docs:sync"; do not edit by hand) -->'
export const HELP_END = '<!-- cli-help:end -->'

export function renderHelpBlock(): string {
  return ['```', formatHelp(TOOL_DEFINITIONS), '```'].join('\n')
}

export function syncReadme(readme: string): string {
  const from = readme.indexOf(HELP_START)
  const to = readme.indexOf(HELP_END)

  if (from < 0 || to < from) {
    throw new Error('README is missing the cli-help start/end markers')
  }

  return `${readme.slice(0, from + HELP_START.length)}\n${renderHelpBlock()}\n${readme.slice(to)}`
}
